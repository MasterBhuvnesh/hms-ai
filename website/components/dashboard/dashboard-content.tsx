"use client";

import { useState } from "react";
import { HugeiconsIcon } from "@hugeicons/react";
import { AiMagicIcon, FileExportIcon } from "@hugeicons/core-free-icons";
import { Button } from "@/components/ui/button";
import { Card } from "@/components/ui/card";
import { KpiCard, MoreButton, PanelTitle } from "@/components/dashboard/cards";
import { RevenueBars } from "@/components/dashboard/charts";
import { DateControls } from "@/app/date-controls";
import { SalesTrend } from "@/app/sales-trend";
import { TransactionsView } from "@/app/transactions/transactions-view";
import { useCurrentRole } from "@/components/dashboard/use-current-role";
import { dashboardAccess } from "@/lib/permissions";
import { hospitalKpis } from "@/data/hospital";
import { downloadCsv } from "@/lib/export-csv";
import data from "@/data/dashboard.json";

const monthDate = new Date(data.date);
const daysInMonth = new Date(monthDate.getFullYear(), monthDate.getMonth() + 1, 0).getDate();

function exportOverview(role: string): void {
  downloadCsv("hospital-overview", [
    ["Section", "Label", "Value", "Detail"],
    ...hospitalKpis.map((k) => ["KPI", k.label, k.value, `${k.delta} ${k.deltaLabel}`]),
    ["Meta", "Report date", data.date, ""],
    ["Meta", "Generated by role", role, ""],
  ]);
}

function AdmissionsBody() {
  const role = useCurrentRole();
  const [days, setDays] = useState(daysInMonth);
  const [insight, setInsight] = useState<string | null>(null);
  const [aiLoading, setAiLoading] = useState(false);
  const [aiError, setAiError] = useState<string | null>(null);

  async function getInsight() {
    if (aiLoading) return;
    setAiLoading(true);
    setAiError(null);
    try {
      const res = await fetch("/api/ai/chat", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          role,
          user: "staff",
          messages: [
            {
              role: "user",
              content: `Summarize today's hospital admissions load in 3 short sentences for a ${role}: 184 patients today, bed occupancy 78%, average wait 18 minutes. Flag the biggest bottleneck.`,
            },
          ],
        }),
      });
      const payload = (await res.json()) as { reply?: string; error?: string };
      if (!res.ok || !payload.reply) throw new Error(payload.error || "ai_failed");
      setInsight(payload.reply);
    } catch (err) {
      setAiError(err instanceof Error ? err.message : "AI unavailable right now.");
    } finally {
      setAiLoading(false);
    }
  }

  return (
    <div className="flex-1 space-y-4 rounded-xl bg-card p-4">
      <div className="flex items-end justify-between gap-2">
        <div>
          <p className="text-sm text-muted-foreground">Patients by Department</p>
          <p className="mt-1 font-mono text-2xl font-semibold tracking-tight">
            184 today
          </p>
        </div>
        <div className="flex gap-1 rounded-full border p-1">
          {[7, 14, 30].map((d) => (
            <Button
              key={d}
              variant={days === d ? "default" : "ghost"}
              size="sm"
              className="rounded-full"
              onClick={() => setDays(d)}
              aria-label={`Show last ${d} days`}
            >
              {d}d
            </Button>
          ))}
        </div>
      </div>
      <button
        onClick={() => void getInsight()}
        disabled={aiLoading}
        className="flex w-full items-center gap-2.5 rounded-xl bg-muted p-2 text-left text-sm text-muted-foreground hover:bg-muted/70 disabled:opacity-60"
      >
        <span className="flex size-7 shrink-0 items-center justify-center rounded-lg border bg-card">
          <HugeiconsIcon icon={AiMagicIcon} size={14} className={aiLoading ? "animate-pulse" : undefined} />
        </span>
        {aiLoading
          ? "Analyzing admissions..."
          : (insight ?? "Get AI insight for better analysis")}
      </button>
      {aiError && <p className="text-xs text-red-500">{aiError}</p>}
      <RevenueBars bars={data.revenueBreakdown.bars.slice(-days)} />
      <div className="flex items-center justify-between border-t pt-3 font-sans text-[10px] tracking-wide text-muted-foreground uppercase">
        <span>Last {days} days</span>
        <span>{data.date}</span>
      </div>
    </div>
  );
}

export function DashboardContent() {
  const role = useCurrentRole();
  const access = dashboardAccess(role);
  const kpis = hospitalKpis.filter((kpi) => access.kpis.includes(kpi.label));

  return (
    <>
      <div className="flex flex-wrap items-center justify-between gap-4">
        <div>
          <h1 className="text-2xl font-medium tracking-tight">
            CityCare Hospital Overview
          </h1>
          <p className="text-sm text-muted-foreground">
            Welcome back, {data.user.firstName} - viewing as {role}. {access.note}
          </p>
        </div>
        <div className="flex flex-wrap items-center gap-2">
          <DateControls initialDate={data.date} />
          <Button size="lg" onClick={() => exportOverview(role)}>
            <HugeiconsIcon icon={FileExportIcon} size={14} data-icon="inline-start" />
            Export Report
          </Button>
        </div>
      </div>

      <div className="grid gap-4 sm:grid-cols-2 xl:grid-cols-4">
        {kpis.map((kpi) => (
          <KpiCard key={kpi.label} kpi={kpi} />
        ))}
      </div>

      {access.showAdmissions && (
        <div className="grid gap-4 xl:grid-cols-3">
          <SalesTrend />

          <Card className="gap-0 bg-muted/50 p-1 ring-0 shadow-sm dark:bg-muted">
            <div className="flex items-center justify-between px-3 py-2">
              <PanelTitle title="Admissions Breakdown" />
              <MoreButton />
            </div>
            <AdmissionsBody />
          </Card>
        </div>
      )}

      {access.showPayments && <TransactionsView title="Recent Payments" showAdd />}
    </>
  );
}
